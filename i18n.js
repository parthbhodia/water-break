function wbResolveLang(setting) {
  if (setting && WB_I18N[setting]) return setting;
  const ui = (chrome.i18n?.getUILanguage?.() || navigator.language || 'en').toLowerCase();
  if (ui.startsWith('zh')) return /tw|hk|mo|hant/.test(ui) ? 'zhTW' : 'zh';
  let base = ui.split('-')[0];
  if (base === 'tl') base = 'fil';
  return WB_I18N[base] ? base : 'en';
}

function wbT(lang, key, vars = {}) {
  const dict = WB_I18N[lang] || WB_I18N.en;
  const raw = dict[key] ?? WB_I18N.en[key] ?? key;
  if (typeof raw !== 'string') return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

function wbMessages(lang) {
  return (WB_I18N[lang] || WB_I18N.en).messages;
}

const WB_RTL = new Set(['ur']);
function wbIsRtl(lang) {
  return WB_RTL.has(lang);
}
